// Mission-mode store screenshots (1920×1080): task card, narration, battle, heart lost, task complete.
import { chromium } from '@playwright/test';
import fs from 'node:fs';
const base = process.argv[2] ?? 'http://127.0.0.1:4173';
fs.mkdirSync('store/screenshots', { recursive: true });
const browser = await chromium.launch({ headless: true, args: ['--use-gl=angle', '--use-angle=metal', '--ignore-gpu-blocklist', '--autoplay-policy=no-user-gesture-required'] });
const page = await browser.newPage({ viewport: { width: 1920, height: 1080 }, deviceScaleFactor: 1 });
const shot = (f) => page.screenshot({ path: `store/screenshots/${f}.png` }).then(() => console.log('wrote', f));
await page.goto(`${base}/?scene=game`, { waitUntil: 'load' });
await page.waitForFunction(() => window.__eka?.ready === true, null, { timeout: 90000 });
await page.waitForTimeout(1500);
await page.click('#boot-continue');
await page.waitForFunction(() => window.__eka.mission().narrating === true, null, { timeout: 30000 });
await page.waitForFunction(() => (document.querySelector('.narration-text')?.textContent ?? '').endsWith('Task 1.'), null, { timeout: 15000 });
await page.waitForTimeout(400);
await shot('13-task-1-card');
await page.evaluate(() => document.dispatchEvent(new KeyboardEvent('keydown', { code: 'Space', bubbles: true })));
await page.keyboard.press('Space');
await page.waitForTimeout(3200);
await shot('14-villain-narration');
await page.evaluate(() => window.__eka.missionSkipNarration());
await page.waitForFunction(() => window.__eka.mission().phase === 'battle', null, { timeout: 40000 });
await page.waitForTimeout(5000);
const aim = async () => {
  const m = await page.evaluate(() => window.__eka.mission());
  const p = await page.evaluate(() => window.__eka.playerPosition());
  const cam = await page.evaluate(() => window.__eka.cameraPosition());
  const yaw = Math.atan2(-(m.bossPos[0] - p.x), -(m.bossPos[2] - p.z));
  const pitch = -Math.atan2(m.bossPos[1] + 2 - cam.y, Math.hypot(m.bossPos[0] - cam.x, m.bossPos[2] - cam.z));
  await page.evaluate(([y, pch]) => window.__eka.setCamera(y, pch + 0.12), [yaw, pitch]);
};
await aim();
await page.waitForTimeout(500);
await page.evaluate(() => { const c = document.getElementById('game'); c.dispatchEvent(new MouseEvent('mousedown', { button: 0, bubbles: true })); });
await page.waitForTimeout(240);
await shot('15-battle-matsarasura');
await page.evaluate(() => { const c = document.getElementById('game'); c.dispatchEvent(new MouseEvent('mouseup', { button: 0, bubbles: true })); });
await page.evaluate(() => window.__eka.missionHurtPlayer(500));
await page.waitForTimeout(500);
await shot('16-heart-lost');
await page.waitForFunction(() => window.__eka.mission().phase === 'battle', null, { timeout: 20000 });
await page.waitForTimeout(2000);
await page.evaluate(() => window.__eka.missionDamageBoss(10000));
await page.waitForTimeout(4600);
await aim().catch(() => {});
await page.waitForTimeout(300);
await shot('17-task-complete');
await page.waitForFunction(() => window.__eka.mission().task === 2 && window.__eka.mission().narrating === true, null, { timeout: 30000 });
await page.waitForTimeout(3500);
await page.keyboard.press('Space');
await page.waitForTimeout(3000);
await shot('18-task-2-madasura');
await browser.close();
